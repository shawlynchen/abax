// ---------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------

const ZEROR: f64 = 0.0;
const ZEROI: f64 = 0.0;
const CONER: f64 = 1.0;
const CONEI: f64 = 0.0;
const EX1: f64 = 3.33333333333333333e-01;
const EX2: f64 = 6.66666666666666667e-01;
const HPI: f64 = 1.57079632679489662e+00;
const GPI: f64 = 3.14159265358979324e+00;
const THPI: f64 = 4.71238898038468986e+00;

/// ZUNHJ computes parameters for Bessel functions C(FNU,Z) = J(FNU,Z),
/// Y(FNU,Z) or H(I,FNU,Z) I=1,2 for large orders FNU by means of the
/// uniform asymptotic expansion
///
///     C(FNU,Z) = C1*PHI*( ASUM*AIRY(ARG) + C2*BSUM*DAIRY(ARG) )
///
/// for proper choices of C1, C2, AIRY and DAIRY where AIRY is an
/// Airy function and DAIRY is its derivative.
///
///     (2/3)*FNU*ZETA**1.5 = ZETA1 - ZETA2,
///
/// ZETA1 = 0.5*FNU*CLOG((1+W)/(1-W)), ZETA2 = FNU*W for scaling
/// purposes in Airy functions from CAIRY or CBIRY.
///
/// MCONJ = SIGN OF AIMAG(Z), but is ambiguous when Z is real and must
/// be specified. IPMTR=0 returns all parameters. IPMTR=1 computes all
/// except ASUM and BSUM.
#[allow(clippy::too_many_arguments)]
pub(crate) fn zunhj(
    zr: f64,
    zi: f64,
    fnu: f64,
    ipmtr: i32,
    tol: f64,
    phir: &mut f64,
    phii: &mut f64,
    argr: &mut f64,
    argi: &mut f64,
    zeta1r: &mut f64,
    zeta1i: &mut f64,
    zeta2r: &mut f64,
    zeta2i: &mut f64,
    asumr: &mut f64,
    asumi: &mut f64,
    bsumr: &mut f64,
    bsumi: &mut f64,
) {
    let rfnu = 1.0 / fnu;

    // Overflow test (Z/FNU too small)
    let test = d1mach(1) * 1.0e+3;
    let ac = fnu * test;
    if zr.abs() <= ac && zi.abs() <= ac {
        *zeta1r = 2.0 * test.abs().ln() + fnu;
        *zeta1i = 0.0;
        *zeta2r = fnu;
        *zeta2i = 0.0;
        *phir = 1.0;
        *phii = 0.0;
        *argr = 1.0;
        *argi = 0.0;
        return;
    }

    let zbr = zr * rfnu;
    let zbi = zi * rfnu;
    let rfnu2 = rfnu * rfnu;

    // Compute in the fourth quadrant
    let fn13 = fnu.powf(EX1);
    let fn23 = fn13 * fn13;
    let rfn13 = 1.0 / fn13;
    let w2r = CONER - zbr * zbr + zbi * zbi;
    let w2i = CONEI - zbr * zbi - zbr * zbi;
    let aw2 = zabs(w2r, w2i);

    if aw2 <= 0.25 {
        // -----------------------------------------------------------------
        // Power series for |W2| <= 0.25
        // -----------------------------------------------------------------
        let mut pr = [0.0f64; 30];
        let mut pi_ = [0.0f64; 30];
        let mut ap = [0.0f64; 30];

        let mut k: usize = 1;
        pr[0] = CONER;
        pi_[0] = CONEI;
        let mut sumar = GAMA[0];
        let mut sumai = ZEROI;
        ap[0] = 1.0;

        if aw2 >= tol {
            for kk in 2..=30 {
                pr[kk - 1] = pr[kk - 2] * w2r - pi_[kk - 2] * w2i;
                pi_[kk - 1] = pr[kk - 2] * w2i + pi_[kk - 2] * w2r;
                sumar += pr[kk - 1] * GAMA[kk - 1];
                sumai += pi_[kk - 1] * GAMA[kk - 1];
                ap[kk - 1] = ap[kk - 2] * aw2;
                if ap[kk - 1] < tol {
                    k = kk;
                    break;
                }
                k = kk;
            }
        }

        let kmax = k;

        let zetar = w2r * sumar - w2i * sumai;
        let zetai = w2r * sumai + w2i * sumar;
        *argr = zetar * fn23;
        *argi = zetai * fn23;

        let (mut zar, mut zai) = (0.0f64, 0.0f64);
        zsqrt(sumar, sumai, &mut zar, &mut zai);
        let (mut str, mut sti) = (0.0f64, 0.0f64);
        zsqrt(w2r, w2i, &mut str, &mut sti);

        *zeta2r = str * fnu;
        *zeta2i = sti * fnu;

        str = CONER + EX2 * (zetar * zar - zetai * zai);
        sti = CONEI + EX2 * (zetar * zai + zetai * zar);
        *zeta1r = str * (*zeta2r) - sti * (*zeta2i);
        *zeta1i = str * (*zeta2i) + sti * (*zeta2r);

        zar += zar;
        zai += zai;
        zsqrt(zar, zai, &mut str, &mut sti);
        *phir = str * rfn13;
        *phii = sti * rfn13;

        if ipmtr != 1 {
            // -------------------------------------------------------------
            // Sum series for ASUM and BSUM
            // -------------------------------------------------------------
            let mut sumbr = ZEROR;
            let mut sumbi = ZEROI;
            for kk in 1..=kmax {
                sumbr += pr[kk - 1] * BETA[kk - 1];
                sumbi += pi_[kk - 1] * BETA[kk - 1];
            }

            *asumr = ZEROR;
            *asumi = ZEROI;
            *bsumr = sumbr;
            *bsumi = sumbi;
            let mut l1: usize = 0;
            let mut l2: usize = 30;
            let btol = tol * (bsumr.abs() + bsumi.abs());
            let mut atol = tol;
            let mut pp = 1.0;
            let mut ias = 0;
            let mut ibs = 0;

            if rfnu2 >= tol {
                for _is in 2..=7 {
                    atol /= rfnu2;
                    pp *= rfnu2;

                    if ias != 1 {
                        sumar = ZEROR;
                        sumai = ZEROI;
                        for kk in 1..=kmax {
                            let m = l1 + kk;
                            sumar += pr[kk - 1] * ALFA[m - 1];
                            sumai += pi_[kk - 1] * ALFA[m - 1];
                            if ap[kk - 1] < atol {
                                break;
                            }
                        }
                        *asumr += sumar * pp;
                        *asumi += sumai * pp;
                        if pp < tol {
                            ias = 1;
                        }
                    }

                    if ibs != 1 {
                        sumbr = ZEROR;
                        sumbi = ZEROI;
                        for kk in 1..=kmax {
                            let m = l2 + kk;
                            sumbr += pr[kk - 1] * BETA[m - 1];
                            sumbi += pi_[kk - 1] * BETA[m - 1];
                            if ap[kk - 1] < atol {
                                break;
                            }
                        }
                        *bsumr += sumbr * pp;
                        *bsumi += sumbi * pp;
                        if pp < btol {
                            ibs = 1;
                        }
                    }

                    if ias == 1 && ibs == 1 {
                        break;
                    }
                    l1 += 30;
                    l2 += 30;
                }
            }

            *asumr += CONER;
            let pp = rfnu * rfn13;
            *bsumr *= pp;
            *bsumi *= pp;
        }

        return;
    }

    // ---------------------------------------------------------------------
    // |W2| > 0.25
    // ---------------------------------------------------------------------
    let (mut wr, mut wi) = (0.0f64, 0.0f64);
    zsqrt(w2r, w2i, &mut wr, &mut wi);
    if wr < 0.0 {
        wr = 0.0;
    }
    if wi < 0.0 {
        wi = 0.0;
    }
    let str = CONER + wr;
    let sti = wi;
    let (mut zar, mut zai) = (0.0f64, 0.0f64);
    zdiv(str, sti, zbr, zbi, &mut zar, &mut zai);
    let (mut zcr, mut zci) = (0.0f64, 0.0f64);
    let _ = zlog(zar, zai, &mut zcr, &mut zci);
    if zci < 0.0 {
        zci = 0.0;
    }
    if zci > HPI {
        zci = HPI;
    }
    if zcr < 0.0 {
        zcr = 0.0;
    }

    let zthr = (zcr - wr) * 1.5;
    let zthi = (zci - wi) * 1.5;
    *zeta1r = zcr * fnu;
    *zeta1i = zci * fnu;
    *zeta2r = wr * fnu;
    *zeta2i = wi * fnu;

    let azth = zabs(zthr, zthi);
    let mut ang = THPI;
    if !(zthr >= 0.0 && zthi < 0.0) {
        ang = HPI;
        if zthr != 0.0 {
            ang = (zthi / zthr).atan();
            if zthr < 0.0 {
                ang += GPI;
            }
        }
    }

    let pp = azth.powf(EX2);
    let ang = ang * EX2;
    let zetar = pp * ang.cos();
    let mut zetai = pp * ang.sin();
    if zetai < 0.0 {
        zetai = 0.0;
    }

    *argr = zetar * fn23;
    *argi = zetai * fn23;

    let (mut rtztr, mut rtztr_i) = (0.0f64, 0.0f64);
    zdiv(zthr, zthi, zetar, zetai, &mut rtztr, &mut rtztr_i);
    zdiv(rtztr, rtztr_i, wr, wi, &mut zar, &mut zai);
    let tzar = zar + zar;
    let tzai = zai + zai;
    let (mut str, mut sti) = (0.0f64, 0.0f64);
    zsqrt(tzar, tzai, &mut str, &mut sti);
    *phir = str * rfn13;
    *phii = sti * rfn13;

    if ipmtr == 1 {
        return;
    }

    let raw = 1.0 / aw2.sqrt();
    let str = wr * raw;
    let sti = -wi * raw;
    let tfnr = str * rfnu * raw;
    let tfni = sti * rfnu * raw;

    let razth = 1.0 / azth;
    let str = zthr * razth;
    let sti = -zthi * razth;
    let rzthr = str * razth * rfnu;
    let rzthi = sti * razth * rfnu;

    let zcr = rzthr * AR[1];
    let zci = rzthi * AR[1];
    let raw2 = 1.0 / aw2;
    let str = w2r * raw2;
    let sti = -w2i * raw2;
    let t2r = str * raw2;
    let t2i = sti * raw2;

    let str = t2r * C[1] + C[2];
    let sti = t2i * C[1];

    let mut upr = [0.0f64; 14];
    let mut upi = [0.0f64; 14];
    let mut crr = [0.0f64; 14];
    let mut cri = [0.0f64; 14];
    let mut drr = [0.0f64; 14];
    let mut dri = [0.0f64; 14];

    upr[1] = str * tfnr - sti * tfni;
    upi[1] = str * tfni + sti * tfnr;

    *bsumr = upr[1] + zcr;
    *bsumi = upi[1] + zci;
    *asumr = ZEROR;
    *asumi = ZEROI;

    if rfnu >= tol {
        let mut przthr = rzthr;
        let mut przthi = rzthi;
        let mut ptfnr = tfnr;
        let mut ptfni = tfni;
        upr[0] = CONER;
        upi[0] = CONEI;
        let mut pp = 1.0;
        let btol = tol * ((*bsumr).abs() + (*bsumi).abs());
        let mut ks: usize = 0;
        let mut kp1: usize = 2;
        let mut l: usize = 3;
        let mut ias = 0;
        let mut ibs = 0;

        for lr in (2..=12).step_by(2) {
            let lrp1 = lr + 1;

            // -------------------------------------------------------------
            // Compute two additional CR, DR, and UP for two more terms in
            // next SUMA and SUMB
            // -------------------------------------------------------------
            for _k in lr..=lrp1 {
                ks += 1;
                kp1 += 1;
                l += 1;
                let mut zar = C[l - 1];
                let mut zai = ZEROI;
                for _j in 2..=kp1 {
                    l += 1;
                    let str = zar * t2r - t2i * zai + C[l - 1];
                    zai = zar * t2i + zai * t2r;
                    zar = str;
                }
                let str = ptfnr * tfnr - ptfni * tfni;
                ptfni = ptfnr * tfni + ptfni * tfnr;
                ptfnr = str;
                upr[kp1 - 1] = ptfnr * zar - ptfni * zai;
                upi[kp1 - 1] = ptfni * zar + ptfnr * zai;

                crr[ks - 1] = przthr * BR[ks];
                cri[ks - 1] = przthi * BR[ks];
                let str = przthr * rzthr - przthi * rzthi;
                przthi = przthr * rzthi + przthi * rzthr;
                przthr = str;
                drr[ks - 1] = przthr * AR[ks + 1];
                dri[ks - 1] = przthi * AR[ks + 1];
            }

            pp *= rfnu2;

            if ias != 1 {
                let mut sumar = upr[lrp1 - 1];
                let mut sumai = upi[lrp1 - 1];
                let mut ju = lrp1;
                for jr in 1..=lr {
                    ju -= 1;
                    sumar += crr[jr - 1] * upr[ju - 1] - cri[jr - 1] * upi[ju - 1];
                    sumai += crr[jr - 1] * upi[ju - 1] + cri[jr - 1] * upr[ju - 1];
                }
                *asumr += sumar;
                *asumi += sumai;
                let test = sumar.abs() + sumai.abs();
                if pp < tol && test < tol {
                    ias = 1;
                }
            }

            if ibs != 1 {
                let mut sumbr = upr[lr + 1] + upr[lrp1 - 1] * zcr - upi[lrp1 - 1] * zci;
                let mut sumbi = upi[lr + 1] + upr[lrp1 - 1] * zci + upi[lrp1 - 1] * zcr;
                let mut ju = lrp1;
                for jr in 1..=lr {
                    ju -= 1;
                    sumbr += drr[jr - 1] * upr[ju - 1] - dri[jr - 1] * upi[ju - 1];
                    sumbi += drr[jr - 1] * upi[ju - 1] + dri[jr - 1] * upr[ju - 1];
                }
                *bsumr += sumbr;
                *bsumi += sumbi;
                let test = sumbr.abs() + sumbi.abs();
                if pp < btol && test < btol {
                    ibs = 1;
                }
            }

            if ias == 1 && ibs == 1 {
                break;
            }
        }
    }

    *asumr += CONER;
    let str = -(*bsumr) * rfn13;
    let sti = -(*bsumi) * rfn13;
    let (mut bsr, mut bsi) = (0.0f64, 0.0f64);
    zdiv(str, sti, rtztr, rtztr_i, &mut bsr, &mut bsi);
    *bsumr = bsr;
    *bsumi = bsi;
}